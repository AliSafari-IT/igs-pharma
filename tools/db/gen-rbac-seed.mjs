/**
 * Prints the SQL that seeds the RBAC catalogue (T-016) from the canonical code catalogue in
 * packages/auth/src/permissions.ts. Paste the output into a new custom migration
 * (`pnpm --filter @igs/db exec drizzle-kit generate --custom --name rbac_seed_<change>`).
 *
 *   node --experimental-strip-types tools/db/gen-rbac-seed.mjs
 *
 * Inserts are idempotent (ON CONFLICT). Removing or renaming a role/permission is never inferred:
 * write that as an explicit fix-forward DELETE/UPDATE in the migration. The real-Postgres drift test
 * (packages/auth/test/rbac.test.ts) fails while the database and the code disagree.
 */
import { PERMISSIONS, ROLES, ROLE_KEYS, codeRolePermissions } from "../../packages/auth/src/permissions.ts";

const q = (value) => `'${String(value).replaceAll("'", "''")}'`;
const permissions = Object.values(PERMISSIONS).flatMap((group) => Object.values(group)).sort();

const lines = [
  "-- RBAC catalogue seed (T-016), generated by tools/db/gen-rbac-seed.mjs from",
  "-- packages/auth/src/permissions.ts. Code is canonical; the drift test compares both.",
  "INSERT INTO identity.roles (key, kind, description) VALUES",
  ROLE_KEYS.map((key) => `  (${q(key)}, ${q(ROLES[key].kind)}, ${q(ROLES[key].description)})`).join(",\n"),
  "ON CONFLICT (key) DO UPDATE SET kind = EXCLUDED.kind, description = EXCLUDED.description;",
  "--> statement-breakpoint",
  "INSERT INTO identity.permissions (key) VALUES",
  permissions.map((key) => `  (${q(key)})`).join(",\n"),
  "ON CONFLICT (key) DO NOTHING;",
  "--> statement-breakpoint",
  "INSERT INTO identity.role_permissions (role_key, permission_key) VALUES",
  codeRolePermissions()
    .map(({ roleKey, permissionKey }) => `  (${q(roleKey)}, ${q(permissionKey)})`)
    .join(",\n"),
  "ON CONFLICT DO NOTHING;",
];
process.stdout.write(`${lines.join("\n")}\n`);
